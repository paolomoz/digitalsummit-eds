/**
 * loads and decorates the footer
 * @param {Element} block The footer block element
 */
export default async function decorate(block) {
  // load footer as fragment
  const footerMeta = getMetadata('footer');
  const footerPath = footerMeta ? new URL(footerMeta, window.location).pathname : '/footer';
  const fragment = await loadFragment(footerPath);

  // decorate footer DOM
  block.textContent = '';
  const footer = document.createElement('div');
  while (fragment.firstElementChild) footer.append(fragment.firstElementChild);

  // social row: swap the plain text links for icon chips (label kept for AT)
  const socials = [...footer.querySelectorAll('a[href]')].filter((a) => {
    try { return Object.keys(SOCIAL_ICONS).some((h) => new URL(a.href).hostname.endsWith(h)); } catch (e) { return false; }
  });
  if (socials.length) {
    const p = socials[0].closest('p');
    if (p) {
      p.classList.add('footer-social');
      socials.forEach((a) => {
        const host = Object.keys(SOCIAL_ICONS).find((h) => new URL(a.href).hostname.endsWith(h));
        const label = a.textContent.trim();
        a.classList.add('footer-social-link');
        a.setAttribute('aria-label', label);
        a.setAttribute('rel', 'noopener');
        a.setAttribute('target', '_blank');
        a.innerHTML = `<span class="footer-social-icon" aria-hidden="true">${SOCIAL_ICONS[host]}</span><span class="footer-social-label">${label}</span>`;
      });
      // drop the “·” separator text nodes between the chips
      [...p.childNodes].forEach((n) => { if (n.nodeType === 3) n.remove(); });
    }
  }

  block.append(footer);
}
